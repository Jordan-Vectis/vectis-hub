// Draws Vectis Scanner's launcher icon: plain white barcode bars on the Goods In indigo. No brand
// artwork — just a generated mark. Writes the adaptive icon's foreground (a vector) and the PNGs
// older Android versions use, into the Android project. Run it only if the icon should change:
//
//   node scripts/make-icons.mjs
//
// No dependencies: the PNGs are encoded here with Node's zlib.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const res = join(root, "android", "app", "src", "main", "res");

const BG = [0x4f, 0x46, 0xe5];
const FG = [0xff, 0xff, 0xff];

// Bars in the adaptive icon's 108 x 108 viewport, inside the 66-unit safe circle.
const TOP = 38;
const BOTTOM = 70;
const pattern = [3, 2, 2, 2, 5, 2, 2, 3, 3, 2, 2, 2, 4, 2, 2, 2, 4]; // bar, gap, bar, gap ... (44 wide)
const bars = [];
{
  let x = 32;
  pattern.forEach((w, i) => {
    if (i % 2 === 0) bars.push([x, x + w]);
    x += w;
  });
}

// 1. Adaptive icon foreground (Android 8+), also used as the themed (monochrome) icon.
const path = bars.map(([a, b]) => `M${a},${TOP}H${b}V${BOTTOM}H${a}Z`).join("");
const vector = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scanner-app/scripts/make-icons.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFF"
        android:pathData="${path}" />
</vector>
`;
mkdirSync(join(res, "drawable"), { recursive: true });
writeFileSync(join(res, "drawable", "ic_launcher_foreground.xml"), vector);

// 2. Legacy PNGs (Android 7.x): a rounded square and a circle.
const CRC_TABLE = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}
function png(size, rgba) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0; // no filter
    rgba.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

function draw(size, round) {
  const SS = 4; // 4 x 4 samples a pixel
  const inset = size * 0.04;
  const box = size - inset * 2;
  const radius = round ? box / 2 : box * 0.2;
  // The viewport's visible middle (18..90) maps onto the inner box.
  const toPx = (v) => inset + ((v - 18) / 72) * box;
  const barPx = bars.map(([a, b]) => [toPx(a), toPx(b)]);
  const top = toPx(TOP);
  const bottom = toPx(BOTTOM);

  const inShape = (x, y) => {
    const lx = Math.min(Math.max(x, inset + radius), inset + box - radius);
    const ly = Math.min(Math.max(y, inset + radius), inset + box - radius);
    if (x < inset || x > inset + box || y < inset || y > inset + box) return false;
    return (x - lx) ** 2 + (y - ly) ** 2 <= radius ** 2;
  };
  const inBar = (x, y) => y >= top && y <= bottom && barPx.some(([a, b]) => x >= a && x <= b);

  const out = Buffer.alloc(size * size * 4);
  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      let shape = 0;
      let bar = 0;
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const x = px + (sx + 0.5) / SS;
          const y = py + (sy + 0.5) / SS;
          if (inShape(x, y)) {
            shape++;
            if (inBar(x, y)) bar++;
          }
        }
      }
      const i = (py * size + px) * 4;
      if (shape === 0) continue;
      const f = bar / shape;
      for (let c = 0; c < 3; c++) out[i + c] = Math.round(BG[c] * (1 - f) + FG[c] * f);
      out[i + 3] = Math.round((shape / (SS * SS)) * 255);
    }
  }
  return png(size, out);
}

const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [name, size] of Object.entries(densities)) {
  const dir = join(res, `mipmap-${name}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "ic_launcher.png"), draw(size, false));
  writeFileSync(join(dir, "ic_launcher_round.png"), draw(size, true));
}
console.log("Icons written to android/app/src/main/res.");
